const mongoose = require('mongoose');
const passwordPlugin = require('./plugins/password');

const AdminSchema = new mongoose.Schema({
  username: {
    type: String,
    required: true,
    unique: true
  },
  email: {
    type: String,
    required: true,
    unique: true,
    lowercase: true
  },
  password: {
    type: String,
    required: true,
    select: false
  },
  fullName: {
    type: String,
    default: 'Administrator'
  },
  role: {
    type: String,
    default: 'admin'
  },
  createdAt: {
    type: Date,
    default: Date.now
  }
});

AdminSchema.plugin(passwordPlugin);

module.exports = mongoose.model('Admin', AdminSchema);
