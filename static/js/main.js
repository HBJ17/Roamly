function setRoamlyLanguage(lang) {
    if (!lang) return;
    try {
        localStorage.setItem('roamly_lang', lang);
    } catch(e) {}
    window.location.href = '/set-lang/' + lang;
}

function applyRoamlyLanguage(lang) {
    if (!lang || lang === 'en' || !ROAMLY_TRANSLATIONS[lang]) return;
    const dict = ROAMLY_TRANSLATIONS[lang];

    // Ensure all language selector dropdowns match the active language
    document.querySelectorAll('.roamly-lang-select, select[title="Language"]').forEach(sel => {
        sel.value = lang;
    });

    // Translate attributes: placeholders, titles, values
    document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(el => {
        const ph = el.getAttribute('placeholder');
        if (!ph) return;
        const trimmed = ph.trim();
        if (dict[trimmed]) {
            el.setAttribute('placeholder', dict[trimmed]);
        } else if (dict[ph]) {
            el.setAttribute('placeholder', dict[ph]);
        }
    });

    document.querySelectorAll('[title]').forEach(el => {
        const t = el.getAttribute('title');
        if (t && t !== 'Language' && t !== 'Currency' && dict[t.trim()]) {
            el.setAttribute('title', dict[t.trim()]);
        }
    });

    // Translate button and submit inputs
    document.querySelectorAll('input[type="submit"], input[type="button"]').forEach(btn => {
        const val = btn.value ? btn.value.trim() : '';
        if (val && dict[val]) {
            btn.value = dict[val];
        }
    });

    // Translate select options (excluding language dropdown options)
    document.querySelectorAll('select:not(.roamly-lang-select):not([title="Language"]) option').forEach(opt => {
        const text = opt.textContent ? opt.textContent.trim() : '';
        if (text && dict[text]) {
            opt.textContent = dict[text];
        }
    });

    // Prepare sorted list of dictionary entries (longest English keys first)
    const sortedEntries = Object.entries(dict).sort((a, b) => b[0].length - a[0].length);

    // Walk through all text nodes in the DOM
    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        {
            acceptNode: function(node) {
                if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
                const parent = node.parentElement;
                if (!parent) return NodeFilter.FILTER_REJECT;
                const tag = parent.tagName.toLowerCase();
                if (tag === 'script' || tag === 'style' || tag === 'select' || parent.classList.contains('roamly-lang-select')) {
                    return NodeFilter.FILTER_REJECT;
                }
                return NodeFilter.FILTER_ACCEPT;
            }
        }
    );

    const textNodes = [];
    while (walker.nextNode()) {
        textNodes.push(walker.currentNode);
    }

    textNodes.forEach(node => {
        let text = node.nodeValue;
        const trimmed = text.trim();
        
        // Exact match replacement
        if (dict[trimmed]) {
            node.nodeValue = text.replace(trimmed, dict[trimmed]);
            return;
        }

        // Case-insensitive exact match
        const lowerTrimmed = trimmed.toLowerCase();
        for (let i = 0; i < sortedEntries.length; i++) {
            const [enKey, trVal] = sortedEntries[i];
            if (enKey.toLowerCase() === lowerTrimmed) {
                node.nodeValue = text.replace(trimmed, trVal);
                return;
            }
        }

        // Substring / compound phrase replacement (sorted by length)
        for (let i = 0; i < sortedEntries.length; i++) {
            const [enKey, trVal] = sortedEntries[i];
            if (enKey.length >= 3 && text.includes(enKey)) {
                text = text.split(enKey).join(trVal);
            }
        }
        node.nodeValue = text;
    });
}

