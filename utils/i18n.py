def translate(key: str, lang: str = 'en') -> str:
    """Retrieve translation for key in selected language with fallback to English."""
    if not lang or lang not in TRANSLATIONS:
        lang = 'en'
    
    # Try exact key lookup in target language
    tr_dict = TRANSLATIONS.get(lang, TRANSLATIONS['en'])
    if key in tr_dict:
        return tr_dict[key]
    
    # Try lowercased / slugified key
    cleaned_key = key.lower().strip().replace(' ', '_')
    if cleaned_key in tr_dict:
        return tr_dict[cleaned_key]
        
    # Fallback to English
    en_dict = TRANSLATIONS.get('en', {})
    if key in en_dict:
        return en_dict[key]
    if cleaned_key in en_dict:
        return en_dict[cleaned_key]
        
    return key
